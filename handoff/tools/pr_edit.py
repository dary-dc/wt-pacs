import json, re, subprocess, sys, urllib.request
# usage: pr_edit.py N  (reads JSON list of [old,new] pairs on stdin; "" old = append); strips Claude footers
n = sys.argv[1]
tok = subprocess.run(["git", "credential", "fill"], input="protocol=https\nhost=github.com\n\n",
                     capture_output=True, text=True).stdout
tok = re.search(r"^password=(.*)$", tok, re.M).group(1)
api = f"https://api.github.com/repos/dary-dc/wt-pacs/pulls/{n}"
hdr = {"Authorization": f"Bearer {tok}", "Accept": "application/vnd.github+json"}
body = json.load(urllib.request.urlopen(urllib.request.Request(api, headers=hdr)))["body"]
for old, new in json.load(sys.stdin):
    if old == "":
        body = body.rstrip() + "\n\n" + new
    else:
        assert body.count(old) == 1, f"#{n}: {old[:60]!r} found {body.count(old)}×"
        body = body.replace(old, new)
body = re.sub(r"\n*🤖 Generated with \[Claude Code\]\(https://claude\.com/claude-code\)\n*", "\n\n", body)
body = re.sub(r"\n*(---\n)?_Generated by \[Claude Code\]\([^)]*\)_\s*$", "\n", body)
body = re.sub(r"\n*https://claude\.ai/code/session_\w+\s*$", "\n", body).rstrip() + "\n"
req = urllib.request.Request(api, data=json.dumps({"body": body}).encode(), headers=hdr, method="PATCH")
print(n, urllib.request.urlopen(req).status)
